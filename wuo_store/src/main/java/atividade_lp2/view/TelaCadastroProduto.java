    public void prepararTela(String acao, String nome, String preco, String quantidade, String avaliacao) {
        this.acaoAtual = acao;
        
        boolean editavel = !acao.equals("DELETAR");
        txtNome.setEditable(editavel);
        txtPreco.setEditable(editavel);
        txtQuantidade.setEditable(editavel);
        btnBom.setEnabled(editavel);
        btnMau.setEnabled(editavel);
        
        switch (acao) {
            case "INSERIR":
                this.setTitle("Cadastrar Produto");
                lblMensagemAcao.setText("Preencha os dados abaixo para adicionar o produto:");
                
                txtNome.setText("");
                txtPreco.setText("");
                txtQuantidade.setText("");
                break;
            
            case "EDITAR":
                this.setTitle("Editar Produto");
                lblMensagemAcao.setText("Altere os campos necessários para realizar as modificações:");
                
                txtNome.setText(nome);
                txtPreco.setText(preco);
                txtQuantidade.setText(quantidade);
                btnBom.setSelected(avaliacao.equals("Bom"));
                btnMau.setSelected(avaliacao.equals("Mau"));
                break;
                
            case "DELETAR":
                this.setTitle("Excluir Produto");
                lblMensagemAcao.setText("Tem certeza que deseja excluir permanentemente este produto?");
                
                txtNome.setText(nome);
                txtPreco.setText(preco);
                txtQuantidade.setText(quantidade);
                btnBom.setSelected(avaliacao.equals("Bom"));
                btnMau.setSelected(avaliacao.equals("Mau"));
                break;
        }
    }
    
