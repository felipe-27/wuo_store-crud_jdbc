    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        
        if (acaoAtual.equals("DELETAR")) {
            controller.deletarProduto();
            this.dispose();      
            return;
        }
        
        // A view apenas coleta os textos brutos
        List<String> produto = new ArrayList<>();
        produto.add(txtNome.getText());
        produto.add(txtPreco.getText());
        produto.add(txtQuantidade.getText());
        String avaliacao = "";
        if (btnBom.isSelected()) {
            avaliacao = btnBom.getText();
        } else if (btnMau.isSelected()) {
            avaliacao = btnMau.getText();
        }

        produto.add(avaliacao);
        
        // Passa a responsabilidade de validar e converter para o Controller
        // O método retornará true se deu tudo certo (para fecharmos a tela)
        boolean sucesso = controller.salvarProduto(acaoAtual, produto);
        
        if (sucesso) {
            this.dispose();
        }
        
    }//GEN-LAST:event_btnConfirmarActionPerformed
