    public TelaPrincipal() {
        setTitle("WuoStore");

        setContentPane(new javax.swing.JPanel() {
            @Override
            protected void paintComponent(java.awt.Graphics g) {
                super.paintComponent(g);
                try {
                    String caminhoImagemFundo = "src/main/java/imagens/fundo_wuostore.png";
                    
                    ImageIcon fundo = new ImageIcon(caminhoImagemFundo);
                    if (fundo.getImageLoadStatus() == java.awt.MediaTracker.COMPLETE) {
                        g.drawImage(fundo.getImage(), 0, 0, getWidth(), getHeight(), this);
                    }
                } catch (Exception e) {
                    System.out.println("Erro ao pintar fundo: " + e.getMessage());
                }
            }
        });
        
        initComponents();
        controller = new ProdutoController(this); // "this" é a referência da TelaPrincipal
        controller.preencherTabela();
        
        DefaultTableModel modelo = (DefaultTableModel) tblProdutos.getModel();
        sorter = new TableRowSorter<>(modelo);
        tblProdutos.setRowSorter(sorter);
        //codigo abaixo é para desativar opção de ordernação que n funciona direito
        sorter.setSortable(0, false);
        sorter.setSortable(1, false);
        sorter.setSortable(2, false);
        sorter.setSortable(3, false);
        sorter.setSortable(4, false);
  
        try {
            String caminhoImagemTitulo = "src/main/java/imagens/titulo_wuostore.png";
            
            ImageIcon iconeOriginal = new ImageIcon(caminhoImagemTitulo);
            
            if (iconeOriginal.getImageLoadStatus() == java.awt.MediaTracker.COMPLETE) {
                Image imagemRedimensionada = iconeOriginal.getImage().getScaledInstance(350, 100, Image.SCALE_SMOOTH);
                lblTitulo.setIcon(new ImageIcon(imagemRedimensionada));
            } else {
                System.out.println("Aviso: O arquivo de imagem não foi encontrado em: " + caminhoImagemTitulo);
                lblTitulo.setText("WuoStore.com"); // Texto alternativo caso a imagem falhe
            }
            
        } catch (Exception e) {
            System.out.println("Erro ao carregar imagem: " + e.getMessage());
        }
    }        
    
