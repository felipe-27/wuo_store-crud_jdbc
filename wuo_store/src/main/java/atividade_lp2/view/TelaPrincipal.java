    public void pesquisar() {
        String texto = txtPesquisa.getText().trim();
        if (texto.isEmpty()) {
            sorter.setRowFilter(null);
            } else {
                sorter.setRowFilter(RowFilter.regexFilter("(?i)" + Pattern.quote(texto), 0));
            }
    }

    private void abrirPopupComProdutoSelecionado(String modoAcao) {
        int linha = tblProdutos.getSelectedRow();
        if (linha == -1) {
            String mensagem = modoAcao.equals("EDITAR") ? "editar." : "deletar.";
            JOptionPane.showMessageDialog(this, "Selecione um produto para " + mensagem);
            return;
        }
        
        String nome = tblProdutos.getValueAt(linha, 0).toString();
        String preco = tblProdutos.getValueAt(linha, 1).toString();
        String quantidade = tblProdutos.getValueAt(linha, 2).toString();
        String avaliacao = tblProdutos.getValueAt(linha, 3).toString();
        
        TelaCadastroProduto popup = new TelaCadastroProduto(this, true);
        popup.prepararTela(modoAcao, nome, preco, quantidade, avaliacao);
        popup.setLocationRelativeTo(this);
        popup.setVisible(true);
    }
    
